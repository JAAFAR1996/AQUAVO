import Beasties from "beasties";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

/** Extract from the actual rendered tree; never maintain a second home stylesheet. */
export async function generateHomeStylesModule(template: string, shell: string): Promise<void> {
  const links = template.match(/<link\b[^>]*rel="stylesheet"[^>]*>/g) ?? [];
  if (links.length !== 1) throw new Error("Expected one storefront stylesheet in the Vite template");
  const href = links[0].match(/href="([^"]+)"/)?.[1];
  if (!href?.startsWith("/assets/")) throw new Error("Expected a local versioned storefront stylesheet");
  const path = resolve("dist/public", `.${href}`);
  const original = await readFile(path, "utf8");
  const initialStyles = new Set([...template.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)].map(match => match[1]));
  // Both themes and every media query are eligible, independent of build size.
  const document = template
    .replace("<html ", '<html class="aq-js light dark" ')
    .replace(/(<div id="root"[^>]*>)\s*(<\/div>)/, (_match, open: string, close: string) => open + shell + close);
  const result = await new Beasties({
    path: resolve("dist/public"), publicPath: "/", remote: false,
    preload: "media", pruneSource: false, reduceInlineStyles: false,
    mergeStylesheets: false, inlineFonts: false, preloadFonts: false,
    // The first-visit reveal starts before hydration and lives outside #root.
    // Include its existing styles even though the server tree omits that node.
    allowRules: [/^:root/, /^html\.light\b/, /^html\.dark\b/, /^\.dark$/, /\.aqv-first-dive/], logLevel: "warn",
  }).process(document);
  const css = [...result.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)]
    .map(match => match[1]).filter(style => !initialStyles.has(style)).join("\n");
  if (!css.includes("aq-waterline-hero") || Buffer.byteLength(css) > 120_000 || /<\/style/i.test(css)) {
    throw new Error("Home critical stylesheet failed its content/size safety checks");
  }
  if (await readFile(path, "utf8") !== original) throw new Error("Critical extraction modified the full stylesheet");
  await writeFile("api/_home-critical-css.ts", "// AUTO-GENERATED by script/prerender-home-styles.ts — do not edit\n" +
    `export const HOME_STYLESHEET_HREF = ${JSON.stringify(href)};\n` +
    `export const HOME_CRITICAL_CSS = ${JSON.stringify(css)};\n`);
  console.log(`Home critical CSS: ${Buffer.byteLength(css)} bytes; complete stylesheet retained unchanged`);
}

import { db } from '../server/db.js';
import { products } from '../shared/schema.js';
import { eq } from 'drizzle-orm';

async function fixSucker() {
  const slug = 'houyi-sucker-buckle';
  const newName = 'شفاطات جدارية قوية لتثبيت الأنابيب والسخانات';
  const newDesc = `تخلص من فوضى الأسلاك والأنابيب داخل حوضك!
صُممت هذه الشفاطات الجدارية (Suction Cups) من مطاط مرن وعالي الجودة لضمان أقصى درجات الثبات والالتصاق على زجاج الحوض.

✨ الفوائد الرئيسية:
• ثبات فائق: لا تنزلق أو تتيبس حتى مع الغمر المستمر تحت الماء لفترات طويلة.
• مرونة ممتازة: تصميم هندسي مبتكر يثبت أنابيب الفلاتر، خراطيم هواء الأكسجين، وسخانات المياه بأمان تام.
• مظهر احترافي: ترتب الأسلاك والأنابيب خلف الحوض وفي الزوايا، لتمنح أسماكك بيئة آمنة وحوضك منظراً سينمائياً خالياً من الفوضى.
• سهولة التركيب: اضغطها على الزجاج الداخلي فقط! ويمكن تحريكها بسهولة أثناء التنظيف دون ترك أي أثر.`;

  console.log('🔄 جاري حقن الوصف الاحترافي الجديد في قاعدة البيانات...');
  await db.update(products).set({
    name: newName,
    description: newDesc
  }).where(eq(products.slug, slug));

  console.log('✅ تم مسح الترجمة الركيكة، وتمت إضافة الوصف والاسم التسويقي الجديد بنجاح!');
  process.exit(0);
}

fixSucker().catch(console.error);

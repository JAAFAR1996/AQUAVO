import { build } from "esbuild";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

/** Build the real anonymous home tree, without executing effects or API calls. */
export async function generateHomeShellModule(): Promise<void> {
  const entry = resolve("generated/home-shell-entry.tsx");
  const bundle = resolve("generated/home-shell-entry.mjs");
  await mkdir("generated", { recursive: true });
  try {
    await writeFile(entry, `
import { renderToPipeableStream } from "react-dom/server";
import { PassThrough } from "node:stream";
import { Router } from "wouter";
import { StorefrontRoot } from "../client/src/storefront-root";
export function render() {
  return new Promise<string>((resolve, reject) => {
    const output = new PassThrough();
    let html = "";
    output.setEncoding("utf8");
    output.on("data", (chunk: string) => { html += chunk; });
    output.on("end", () => resolve(html));
    output.on("error", reject);
    const stream = renderToPipeableStream(<Router ssrPath="/"><StorefrontRoot hasInitialShell /></Router>, {
      onAllReady() { stream.pipe(output); },
      onError(error: unknown) { reject(error); },
    });
  });
}
`);
    await build({
      entryPoints: [entry], outfile: bundle, platform: "node", format: "esm",
      bundle: true, packages: "external", jsx: "automatic", logLevel: "silent",
      loader: { ".css": "empty", ".png": "dataurl", ".jpg": "dataurl", ".svg": "dataurl" },
      define: { "process.env.NODE_ENV": '"production"', "import.meta.env": "{}" },
      alias: { "@": resolve("client/src"), "@shared": resolve("shared") },
      banner: { js: "import { createRequire } from 'node:module';const require = createRequire(import.meta.url);" },
    });
    const renderer = await import(`${pathToFileURL(bundle).href}?t=${Date.now()}`) as { render: () => Promise<string> };
    // The document head owns resource preloads. Keep the React tree and its
    // Suspense/useId markers intact so hydration can reuse the original nodes.
    const html = (await renderer.render()).replace(/<link\b[^>]*rel="preload"[^>]*\/>/g, "");
    if (!html.includes("aq-site-header") || !html.includes("aq-waterline-hero") || html.includes("<template")) {
      throw new Error("Home shell prerender did not produce a complete hydratable page");
    }
    await writeFile("api/_home-shell-html.ts", "// AUTO-GENERATED by script/prerender-home-shell.ts — do not edit\n" +
      `export const HOME_SHELL_HTML = ${JSON.stringify(html)};\n`);
  } finally {
    await rm(entry, { force: true });
    await rm(bundle, { force: true });
  }
}

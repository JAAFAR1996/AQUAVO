async function run() {
  console.log("Phase 1: Fixing slugs and excerpts...");
  const posts = await db.query.blogPosts.findMany();
  let updated = 0;

  for (const post of posts) {
    const fix = fixes[post.slug];
    if (fix) {
      const updateData: any = {};
      if (fix.slug) updateData.slug = fix.slug;
      if (fix.excerpt) updateData.excerpt = fix.excerpt;

      await db.update(blogPosts)
        .set(updateData)
        .where(eq(blogPosts.id, post.id));
      updated++;
      console.log(`✅ Fixed: ${post.title} -> slug: ${fix.slug || post.slug}`);
    }
  }

  console.log(`\n🎉 Phase 1 done! Updated ${updated} posts.`);
  process.exit(0);
}

run();

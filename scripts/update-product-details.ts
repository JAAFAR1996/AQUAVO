async function updateProductDetails() {
    console.log("🔌 Connecting to NEON database...");
    const client = neon(DATABASE_URL);
    const db = drizzle(client);

    console.log("📝 Updating products with detailed specifications...\n");

    let successCount = 0;
    let failCount = 0;

    for (const update of productUpdates) {
        try {
            // Find product by name (case insensitive like match)
            const [existingProduct] = await db
                .select()
                .from(products)
                .where(ilike(products.name, `%${update.nameLike.substring(0, 30)}%`))
                .limit(1);

            if (!existingProduct) {
                console.log(`⚠️ Product not found: ${update.nameLike}`);
                failCount++;
                continue;
            }

            // Update the product
            await db
                .update(products)
                .set({
                    description: update.description,
                    specifications: update.specifications,
                    isNew: true
                })
                .where(eq(products.id, existingProduct.id));

            console.log(`✅ Updated: ${existingProduct.name}`);
            successCount++;
        } catch (error: any) {
            console.error(`❌ Failed to update: ${update.nameLike}`);
            console.error(`   Error: ${error.message}\n`);
            failCount++;
        }
    }

    console.log("\n" + "═".repeat(50));
    console.log(`\n📊 Results:`);
    console.log(`   ✅ Success: ${successCount}`);
    console.log(`   ❌ Failed: ${failCount}`);
    console.log(`   📦 Total: ${productUpdates.length}`);
}

updateProductDetails().catch(console.error);

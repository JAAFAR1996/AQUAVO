async function updateHygger() {
    console.log("🚀 Starting Bulk Update for 17 Hygger products...");

    const db = getDb();
    if (!db) process.exit(1);

    let successCount = 0;

    for (const [id, data] of Object.entries(updates)) {
        try {
            console.log(`Processing: ${id}...`);

            const existing = await db.query.products.findFirst({ where: eq(products.id, id) });

            if (!existing) {
                console.warn(`⚠️ SKIPPED: Product ${id} not found.`);
                continue;
            }

            const newSpecifications = {
                ...data.specs,
                benefits: data.benefits,
                brand: "Hygger"
            };

            await db.update(products)
                .set({
                    name: data.name,
                    description: data.description,
                    specifications: newSpecifications,
                    brand: "Hygger"
                })
                .where(eq(products.id, id));

            console.log(`✅ Updated: ${data.name}`);
            successCount++;

        } catch (error) {
            console.error(`❌ Failed to update ${id}:`, error);
        }
    }

    console.log(`\n🎉 Successfully updated ${successCount} / ${Object.keys(updates).length} Hygger products!`);
    process.exit(0);
}


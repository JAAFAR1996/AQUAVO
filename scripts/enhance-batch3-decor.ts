async function addFieldsToDecor() {
  console.log("=== الدفعة 3 — إضافة حقول لمنتجات الديكور ===\n");
  let ok = 0, skip = 0, fail = 0;

  for (const u of updates) {
    try {
      const rows = await sql`SELECT specifications FROM products WHERE id = ${u.id}`;
      if (!rows.length) { console.log(`⚠ لم يُعثر: ${u.id}`); skip++; continue; }

      const specs = rows[0].specifications as Record<string, any> || {};

      // تحويل المفتاح القديم إذا وُجد
      if (specs["لماذا تختار هذا المنتج"] && !specs["benefits"]) {
        specs["benefits"] = specs["لماذا تختار هذا المنتج"];
        delete specs["لماذا تختار هذا المنتج"];
      }

      // إضافة benefits إذا لم تكن موجودة
      if (!specs["benefits"]) specs["benefits"] = u.benefits;

      specs["usageInstructions"] = u.usageInstructions;
      specs["safetyWarnings"] = u.safetyWarnings;

      await sql`UPDATE products SET specifications = ${JSON.stringify(specs)}::jsonb, updated_at = NOW() WHERE id = ${u.id}`;
      console.log(`✓ ${u.id}`);
      ok++;
    } catch (e: any) {
      console.error(`✗ ${u.id}: ${e.message}`);
      fail++;
    }
  }
  console.log(`\n=== اكتمل === تم: ${ok} | تخطي: ${skip} | فشل: ${fail}`);
}


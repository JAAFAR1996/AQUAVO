async function main() {
  console.log("=== PERFECTING YEE PRODUCTS ===\n");

  // Step 1: Update all product names, descriptions, categories
  console.log("📝 Step 1: Updating Arabic names and descriptions...\n");
  let updateCount = 0;

  for (const [slug, data] of Object.entries(productUpdates)) {
    try {
      const result = await sql`
        UPDATE products SET
          name = ${data.name},
          description = ${data.description},
          category = ${data.category},
          subcategory = ${data.subcategory},
          updated_at = NOW()
        WHERE slug = ${slug}
        RETURNING id
      `;
      if (result.length > 0) {
        console.log(`✅ ${slug} → ${data.name.substring(0, 50)}...`);
        updateCount++;
      } else {
        console.log(`⚠ ${slug} not found`);
      }
    } catch (err: any) {
      console.log(`❌ ${slug}: ${err.message.substring(0, 60)}`);
    }
  }
  console.log(`\n📊 Updated ${updateCount} products\n`);

  // Step 2: Merge variant groups
  console.log("🔀 Step 2: Merging variant groups...\n");
  let mergedCount = 0;

  for (const group of variantGroups) {
    try {
      // Update main product with variants
      await sql`
        UPDATE products SET
          has_variants = true,
          variants = ${JSON.stringify(group.variants)}::jsonb,
          updated_at = NOW()
        WHERE slug = ${group.mainSlug}
      `;
      console.log(`✅ ${group.mainSlug} → ${group.variants.length} variants`);

      // Delete secondary products
      for (const delSlug of group.deleteSlugs) {
        const del = await sql`DELETE FROM products WHERE slug = ${delSlug} RETURNING slug`;
        if (del.length > 0) {
          console.log(`   🗑️ Removed: ${delSlug}`);
        }
      }
      mergedCount++;
    } catch (err: any) {
      console.log(`❌ ${group.mainSlug}: ${err.message.substring(0, 60)}`);
    }
  }

  // Final summary
  const finalCount = await sql`SELECT count(*) as cnt FROM products`;
  const cats = await sql`SELECT category, count(*) as cnt FROM products GROUP BY category ORDER BY cnt DESC`;

  console.log(`\n${"=".repeat(60)}`);
  console.log(`📊 FINAL SUMMARY`);
  console.log(`${"=".repeat(60)}`);
  console.log(`   ✅ Names updated: ${updateCount}`);
  console.log(`   🔀 Variant groups merged: ${mergedCount}`);
  console.log(`   📦 Total products: ${finalCount[0].cnt}`);
  console.log(`\n   📂 By Category:`);
  for (const c of cats) console.log(`      ${c.category}: ${c.cnt}`);
}


  console.log("🚀  بدء تحديث أسماء وأوصاف المنتجات — اللهجة العراقية 2026...\n");
  let updated = 0;
  let skipped = 0;

  for (const item of updates) {
    for (const id of item.ids) {
      try {
        const specsJson = item.specifications ? JSON.stringify(item.specifications) : null;

        const result = await db.execute(sql`
          UPDATE products
          SET
            name          = ${item.name},
            description   = ${item.description},
            specifications = CASE
              WHEN ${specsJson}::jsonb IS NOT NULL
              THEN ${specsJson}::jsonb
              ELSE specifications
            END,
            updated_at    = NOW()
          WHERE id = ${id}
            AND EXISTS (SELECT 1 FROM products WHERE id = ${id})
        `);

        if ((result as any).rowCount > 0) {
          console.log(`  ✅  ${id}  →  ${item.name}`);
          updated++;
        } else {
          console.log(`  ⚠️   ${id}  (غير موجود — تخطّي)`);
          skipped++;
        }
      } catch (err) {
        console.error(`  ❌  ${id}:`, (err as Error).message);
      }
    }
  }

  console.log(`\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━`);

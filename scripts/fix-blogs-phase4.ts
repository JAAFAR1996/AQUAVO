async function run() {
  console.log("Phase 4: Expanding remaining short posts...");
  const posts = await db.query.blogPosts.findMany();
  let expanded = 0;

  for (const post of posts) {
    const newContent = expansions[post.slug];
    if (newContent) {
      await db.update(blogPosts)
        .set({ content: newContent.trim() })
        .where(eq(blogPosts.id, post.id));
      expanded++;
      console.log(`✅ Expanded: ${post.title} (${post.content.length} -> ${newContent.trim().length} chars)`);
    }
  }

  console.log(`\n🎉 Phase 4 done! Expanded ${expanded} more posts.`);
  process.exit(0);
}

run();

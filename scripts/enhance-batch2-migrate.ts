async function migrateProducts() {
  console.log("=== بدء تحويل وإضافة الحقول الجديدة ===\n");

  let updated = 0;
  let failed = 0;

  for (const product of updates) {
    try {
      // 1. جلب المواصفات الحالية
      const rows = await sql`SELECT specifications FROM products WHERE id = ${product.id}`;
      if (rows.length === 0) {
        console.log(`⚠ لم يُعثر على: ${product.id}`);
        continue;
      }

      const specs = rows[0].specifications as Record<string, any> || {};

      // 2. تحويل "لماذا تختار هذا المنتج" إلى "benefits" إذا لم يكن موجوداً
      if (specs["لماذا تختار هذا المنتج"] && !specs["benefits"]) {
        specs["benefits"] = specs["لماذا تختار هذا المنتج"];
        delete specs["لماذا تختار هذا المنتج"];
      }

      // 3. إضافة الحقول الجديدة
      specs["usageInstructions"] = product.usageInstructions;
      specs["safetyWarnings"] = product.safetyWarnings;

      // 4. حفظ التحديث
      await sql`
        UPDATE products
        SET specifications = ${JSON.stringify(specs)}::jsonb, updated_at = NOW()
        WHERE id = ${product.id}
      `;
      console.log(`✓ تم تحديث: ${product.id}`);
      updated++;
    } catch (error: any) {
      console.error(`✗ فشل: ${product.id}: ${error.message}`);
      failed++;
    }
  }

  console.log(`\n=== اكتمل ===`);
  console.log(`تم: ${updated} | فشل: ${failed}`);
}

migrateProducts().then(() => process.exit(0)).catch(e => { console.error(e); process.exit(1); });

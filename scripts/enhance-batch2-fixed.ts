async function migrateProducts() {
  console.log("=== بدء التحديث بالـ IDs الصحيحة ===\n");
  let updated = 0, skipped = 0, failed = 0;

  for (const product of updates) {
    try {
      const rows = await sql`SELECT specifications FROM products WHERE id = ${product.id}`;
      if (rows.length === 0) { console.log(`⚠ لم يُعثر: ${product.id}`); skipped++; continue; }

      const specs = rows[0].specifications as Record<string, any> || {};

      // تحويل المفتاح القديم إلى الجديد
      if (specs["لماذا تختار هذا المنتج"] && !specs["benefits"]) {
        specs["benefits"] = specs["لماذا تختار هذا المنتج"];
        delete specs["لماذا تختار هذا المنتج"];
      }

      specs["usageInstructions"] = product.usageInstructions;
      specs["safetyWarnings"] = product.safetyWarnings;

      await sql`
        UPDATE products SET specifications = ${JSON.stringify(specs)}::jsonb, updated_at = NOW()
        WHERE id = ${product.id}
      `;
      console.log(`✓ ${product.id}`);
      updated++;
    } catch (error: any) {
      console.error(`✗ ${product.id}: ${error.message}`);
      failed++;
    }
  }

  console.log(`\n=== اكتمل === تم: ${updated} | تخطي: ${skipped} | فشل: ${failed}`);
}


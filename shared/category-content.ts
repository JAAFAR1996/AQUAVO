/**
 * The editorial block for a category, or undefined when the category is not
 * one of the eleven. Undefined means "render nothing": generic filler under a
 * category it was not written for is worse than the template it replaces.
 */
export function categoryContent(category: string | null | undefined): CategoryContent | undefined {
  const canonical = canonicalProductCategory(category);
  return canonical ? CATEGORY_CONTENT[canonical] : undefined;
}

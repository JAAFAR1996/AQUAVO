/** The search presentation for a category, or undefined when it is not one of the eleven. */
export function categorySearch(category: string | null | undefined): CategorySearch | undefined {
  const canonical = canonicalProductCategory(category);
  return canonical ? CATEGORY_SEARCH[canonical] : undefined;
}

/** FAQPage node for a category listing, or null when the category has no questions. */
export function categoryFaqSchema(category: string | null | undefined): object | null {
  const content = categorySearch(category);
  if (!content) return null;
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: content.faq.map((item) => ({
      "@type": "Question",
      name: item.question,
      acceptedAnswer: { "@type": "Answer", text: item.answer },
    })),
  };
}

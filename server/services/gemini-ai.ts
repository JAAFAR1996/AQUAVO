const CART_INTENT_KEYWORDS = [
    "ضيفها للسلة", "ضيفه للسلة", "ضيفهم للسلة",
    "ضيفها لل سلة", "ضيفه لل سلة", "ضيفهم لل سلة",
    "حطها بالسلة", "حطه بالسلة", "حطهم بالسلة",
    "حطها بال سلة", "حطه بال سلة",
    "اضيفه", "اضيفها", "اضيف", "ضيفه", "ضيفها", "ضيف",
    "ابي اشتريه", "ابي اشتريها", "ابي اخذه", "ابي اخذها",
    "اريد اشتريه", "اريد اشتريها",
    "خذلي", "خذ لي", "اخذه", "اخذها",
    "شريه", "شريها", "اشتريه", "اشتريها",
    "حطه سلة", "حطها سلة", "بالسلة", "بال سلة",
    "اضافة للسلة", "للسلة", "لل سلة", "add to cart",
];

/**
 * Extract product names from the last assistant message in chat history.
 * Products are usually mentioned as **Name** (bold) in the AI response.
 */
function extractProductNamesFromHistory(history: ChatMessage[]): string[] {
    // Walk backwards to find the last assistant message
    for (let i = history.length - 1; i >= 0; i--) {
        if (history[i].role === "assistant") {
            const text = history[i].content;
            // Extract **bold** product names
            const boldMatches = text.match(/\*\*([^*]+)\*\*/g);
            if (boldMatches && boldMatches.length > 0) {
                return boldMatches
                    .map(m => m.replace(/\*\*/g, "").trim())
                    .filter(name =>
                        // Filter out non-product bold text (section headers, prices, etc.)
                        name.length > 3 &&
                        !name.startsWith("ليش") &&
                        !name.startsWith("شنو") &&
                        !name.includes("د.ع") &&
                        !/^\d/.test(name)
                    );
            }
        }
    }
    return [];
}

async function postExecuteCartAction(
    userMessage: string,
    userId: string | undefined,
    products: any[],
    history: ChatMessage[] = []
): Promise<{ added: boolean; productName?: string; productId?: string }> {
    if (!userId) return { added: false };

    const msg = userMessage.toLowerCase();
    const hasCartIntent = CART_INTENT_KEYWORDS.some(kw => msg.includes(kw));
    if (!hasCartIntent) return { added: false };

    // If no products from current turn, try to find products from chat history
    let availableProducts = products;
    if (availableProducts.length === 0 && history.length > 0) {
        const productNames = extractProductNamesFromHistory(history);
        if (productNames.length > 0) {
            // Search for the mentioned products
            for (const name of productNames.slice(0, 3)) {
                try {
                    const result = await aiToolsExecutor.searchProducts({ query: name, limit: 2 });
                    if (result.success && result.data) {
                        availableProducts = [...availableProducts, ...result.data];
                    }
                } catch { /* best-effort */ }
            }
            // Deduplicate
            availableProducts = availableProducts.filter((p, i, arr) =>
                arr.findIndex(x => x.id === p.id) === i
            );
        }
    }

    if (availableProducts.length === 0) return { added: false };

    // Pick the first product (or try to match "الأول", "الثاني", etc.)
    let targetProduct = availableProducts[0];
    if (msg.includes("الثاني") || msg.includes("ثاني") || msg.includes("التاني")) {
        targetProduct = availableProducts[1] || availableProducts[0];
    } else if (msg.includes("الثالث") || msg.includes("ثالث")) {
        targetProduct = availableProducts[2] || availableProducts[0];
    }

    try {
        const result = await aiToolsExecutor.addToCart({
            userId,
            productId: targetProduct.id,
            quantity: 1,
        });
        if (result.success) {
            return { added: true, productName: targetProduct.name, productId: targetProduct.id };
        }
    } catch (err) {
        console.error("postExecuteCartAction error:", err);
    }
    return { added: false };
}

// ============================================================
// MAIN CHAT FUNCTION - Pre-execute tools approach
// ============================================================

export async function sendMessage(
    message: string,
    history: ChatMessage[] = [],
    context?: ChatContext
): Promise<SendMessageResult> {
    const db = getDb();
    const isAdmin = context?.isAdmin ?? false;
    const userId = context?.userId;
    const sessionId = context?.sessionId;

    try {
        // 1. Fetch customer profile if logged in
        let customerProfile = context?.customerProfile;
        if (userId && !isAdmin && !customerProfile) {
            try {
                const profile = await customerProfiler.getFullProfile(userId);
                customerProfile = profile?.profile;
            } catch {
                // Profile fetch is optional
            }
        }

        // 2. Create system prompt (with context for admin data injection) + inject learnings
        let systemPrompt = createSalesAgentPrompt(context?.userName, customerProfile, isAdmin, context);
        const learnings = await getAppliedLearnings();
        if (learnings) systemPrompt += learnings;

        // 3. Check Groq availability
        if (!groqClient.hasKeys()) {
            return { text: getRandomFallback(), products: [] };
        }

        // 4. Pre-execute tools based on message keywords (for all users)
        let toolProducts: any[] = [];
        let toolContext = "";
        try {
            const toolResult = await preExecuteTools(message, userId);
            toolProducts = toolResult.products;
            toolContext = toolResult.context;
            if (toolProducts.length > 0) {
                aiMonitor.log({ event: "search", level: "info", userId, sessionId, productsFound: toolProducts.length, success: true });
            }
        } catch (toolErr: any) {
            aiMonitor.logError("Tool pre-execution failed", { error: toolErr?.message }, { userId, sessionId, event: "tool_call" });
        }

        // 5. Build message with product context injected
        const userMessageWithContext = toolContext
            ? `${message}\n\n---\n${toolContext}`
            : message;

        // Limit history to last 20 messages to prevent token overflow
        const trimmedHistory = history.slice(-20);

        const groqMessages: GroqChatMessage[] = [
            { role: "system", content: systemPrompt },
            ...trimmedHistory.map(msg => ({
                role: msg.role === "user" ? "user" as const : "assistant" as const,
                content: msg.content
            })),
            { role: "user", content: userMessageWithContext }
        ];

        // 6. Sentiment analysis (fire-and-forget)
        if (userId || sessionId) {
            sentimentAnalyzer.analyzeSentiment(message, userId, sessionId).catch(() => { });
        }

        // 7. Call Groq — use llama-3.3-70b as primary (reliable Arabic, no web interference),
        //    fallback to compound-beta only if llama fails
        const startMs = Date.now();
        let modelUsed = "llama-3.3-70b-versatile";
        let webSearchUsed = false;
        let fallbackUsed = false;

        const response = await withTimeout(
            (async () => {
                try {
                    const res = await groqClient.chat(groqMessages, {
                        model: "llama-3.3-70b-versatile",
                        temperature: 0.45,
                        maxTokens: 2048,
                    });
                    return res;
                } catch (llamaErr: any) {
                    const msg = (llamaErr?.message || "").toLowerCase();
                    const isModelErr = msg.includes("model") || msg.includes("not found") ||
                        msg.includes("does not exist") || msg.includes("unsupported") ||
                        msg.includes("invalid") || msg.includes("rate_limit") || msg.includes("429");
                    if (isModelErr) {
                        console.warn("⚠️ llama-3.3-70b unavailable, falling back to compound-beta");
                        aiMonitor.log({ event: "fallback", level: "warning", userId, sessionId, model: "llama-3.3-70b-versatile", details: { reason: llamaErr?.message } });
                        modelUsed = "compound-beta";
                        fallbackUsed = true;
                        webSearchUsed = true;
                        return await groqClient.chat(groqMessages, {
                            model: "compound-beta",
                            temperature: 0.45,
                            maxTokens: 2048,
                        });
                    }
                    throw llamaErr;
                }
            })(),
            AI_TIMEOUT_MS,
            "انتهت مهلة الاتصال"
        );

        const responseTimeMs = Date.now() - startMs;
        const tokenCount = (response as any).usage?.total_tokens;
        let responseText = response.choices[0]?.message?.content || "";

        // 8. Sanitize response - strip any raw function call tags or leaked context
        responseText = responseText
            .replace(/<function=[^>]*>[\s\S]*?<\/function>/gi, "")
            .replace(/<function=[^>]*\/>/gi, "")
            .replace(/<function=[^>]*>/gi, "")
            .replace(/<\/function>/gi, "")
            .replace(/---\n\[المنتجات المتوفرة[\s\S]*$/gi, "")  // Remove leaked context (format 1)
            .replace(/\[المنتجات المتوفرة[^\n]*\n[\s\S]*$/gi, "") // Remove leaked context (format 2)
            .trim();

        // 9. Normalize to Iraqi dialect — deterministic fallback for any fusha leakage (all users incl. admin)
        responseText = normalizeToIraqiDialect(responseText);

        // Safety check
        if (!responseText || responseText.trim().length === 0) {
            responseText = "عذراً حبيبي، صار خطأ بسيط. كدر تعيد السؤال مرة ثانية؟ 🦐";
            aiMonitor.log({ event: "fallback", level: "warning", userId, sessionId, model: modelUsed, details: { reason: "empty_response" } });
        }

        // Log successful chat
        aiMonitor.log({
            event: "chat", level: "info", model: modelUsed, userId, sessionId,
            responseTimeMs, success: true, tokenCount,
            productsFound: toolProducts.length, fallbackUsed, webSearchUsed,
            messageLength: message.length,
        });

        // 8. Deduplicate products
        const uniqueProducts = toolProducts.filter((p, i, arr) =>
            arr.findIndex(x => x.id === p.id) === i
        );

        // 9. Save conversation to database
        if (db) {
            const conversationId = sessionId || `conv_${Date.now()} `;

            try {
                await db.insert(schema.chatMessages).values({
                    conversationId,
                    userId: userId || null,
                    sessionId,
                    role: "user",
                    content: message,
                });

                await db.insert(schema.chatMessages).values({
                    conversationId,
                    userId: userId || null,
                    sessionId,
                    role: "assistant",
                    content: responseText,
                });

                if (userId) {
                    await customerProfiler.trackInteraction(userId, "chat");
                }
            } catch (saveError) {
                console.error("Failed to save chat:", saveError);
            }
        }

        // 10. Post-execute cart action (if user asked to add to cart)
        const cartAction = await postExecuteCartAction(message, userId, uniqueProducts, history);

        return { text: responseText, products: uniqueProducts, cartAction: cartAction.added ? cartAction : undefined };

    } catch (error) {
        console.error("Groq AI Error:", error);

        if (error instanceof Error) {
            const errorMsg = error.message.toLowerCase();

            const isApiKeyError =
                errorMsg.includes("api_key") ||
                errorMsg.includes("api key") ||
                errorMsg.includes("403") ||
                errorMsg.includes("forbidden") ||
                errorMsg.includes("unregistered") ||
                errorMsg.includes("quota") ||
                errorMsg.includes("rate_limit");

            if (isApiKeyError) {
                console.log("🔄 Attempting to switch to next Groq API key...");
                groqClient.markCurrentKeyFailed(error);
            }
        }

        // Log the error
        const errMsg = error instanceof Error ? error.message : String(error);
        const isTimeout = errMsg.includes("انتهت مهلة") || errMsg.includes("timeout");
        aiMonitor.log({
            event: isTimeout ? "timeout" : "error",
            level: isTimeout ? "warning" : "error",
            success: false, userId, sessionId,
            errorMessage: errMsg,
            errorCode: (error as any)?.status?.toString() ?? (error as any)?.code,
            messageLength: message.length,
        });

        // Always return a friendly fallback instead of throwing
        return { text: getRandomFallback(), products: [] };
    }
}


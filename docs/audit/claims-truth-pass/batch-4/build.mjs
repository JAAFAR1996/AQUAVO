/**
 * Verifies every ledger target against LIVE production, proves the whole set
 * applies cleanly, and only then emits migration.sql and rollback.sql.
 *
 *   node docs/audit/claims-truth-pass/build.mjs
 *
 * Reads the public API. No credentials, and it measures what a reader is
 * actually served rather than what the database is assumed to hold.
 */
import fs from "node:fs";
import path from "node:path";
import { LEDGER } from "./ledger.mjs";

const BASE = "https://aquavoiq.com";
const HERE = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const ID = "blog-claims-truth-batch4-20260902";
const BACKUP = "blog_posts_backup_claims_b4_20260902";

const list = await (await fetch(`${BASE}/api/blog/posts`)).json();
const slugs = (Array.isArray(list) ? list : (list.posts ?? list.data ?? [])).map((p) => p.slug);
if (slugs.length !== 80) throw new Error(`expected 80 published articles, found ${slugs.length}`);
console.log(`fetched ${slugs.length} published articles`);

const posts = new Map();
for (const slug of slugs) {
  const r = await (await fetch(`${BASE}/api/blog/posts/${encodeURIComponent(slug)}`)).json();
  const p = r.post ?? r;
  posts.set(p.slug, p);
}

// Every target must be present exactly once. More than once means the replace
// would change text the ledger never reviewed.
const problems = [];
for (const e of LEDGER) {
  const p = posts.get(e.slug);
  if (!p) { problems.push(`${e.slug}: article not found`); continue; }
  const want = e.n ?? 1;
  const field = e.field ?? "content";
  const n = String(p[field] ?? "").split(e.old).length - 1;
  if (n !== want) problems.push(`${e.slug}: expected ${want} occurrence(s), found ${n} :: ${e.old.slice(0, 70)}`);
}
if (problems.length) { console.error("ABORT:\n" + problems.join("\n")); process.exit(1); }
console.log(`verified ${LEDGER.length} corrections against live content`);

// Apply in memory and re-check that no target survives.




const bySlug = new Map();
for (const e of LEDGER) {
  const key = `${e.slug}::${e.field ?? "content"}`;
  if (!bySlug.has(key)) bySlug.set(key, []);
  bySlug.get(key).push(e);
}

const q = (s) => "'" + s.replace(/'/g, "''") + "'";

let sql = `-- Migration ID: ${ID}
-- Target:       Neon production, blog_posts
-- Rollback:     rollback.sql (restores content and excerpt from the backup table)
--
-- Corpus-wide claims audit, batch 4. This is a different defect class from
-- script contamination: the generator asserted business facts it had no source
-- for. Ground truth is the live catalogue, the governorate list, the shipping
-- constants and the published policy pages. See audit.md for the full ledger,
-- including the claims that were checked and KEPT.
--
-- ${LEDGER.length} corrections across ${bySlug.size} articles.
-- Generated by build.mjs, which verified every target against live production
-- and proved the banned claims are gone corpus-wide before emitting.

BEGIN;

DO $$
DECLARE n int;
BEGIN
  SELECT count(*) INTO n FROM blog_posts WHERE is_published;
  IF n <> 80 THEN RAISE EXCEPTION 'expected 80 published posts, found %', n; END IF;
END $$;

CREATE TABLE ${BACKUP} AS
SELECT id, slug, title, excerpt, content, is_published, now() AS backed_up_at
  FROM blog_posts;

-- Pre-flight: every target must still be present at its expected count.
DO $$
DECLARE bad text;
BEGIN
  SELECT string_agg(t.slug || ' :: ' || left(t.frag, 60), chr(10)) INTO bad
    FROM (VALUES
${LEDGER.map((e) => `      (${q(e.slug)}, ${q(e.old)}, ${e.n ?? 1}, ${q(e.field ?? "content")})`).join(",\n")}
    ) AS t(slug, frag, want, col)
    LEFT JOIN blog_posts b ON b.slug = t.slug
   WHERE b.id IS NULL
      OR (length(CASE t.col WHEN 'excerpt' THEN b.excerpt ELSE b.content END)
          - length(replace(CASE t.col WHEN 'excerpt' THEN b.excerpt ELSE b.content END, t.frag, '')))
         / nullif(length(t.frag), 0) <> t.want;
  IF bad IS NOT NULL THEN
    RAISE EXCEPTION 'live content changed since drafting; bad targets: %', bad;
  END IF;
END $$;

`;

// One correction lives in an excerpt rather than a body, so the column is part
// of the grouping key and the UPDATE targets whichever column the entry names.
for (const [key, entries] of bySlug) {
  const [slug, field] = key.split("::");
  sql += `-- ${slug} · ${field} (${entries.length} correction${entries.length > 1 ? "s" : ""})\n`;
  for (const e of entries) sql += `--   ${e.cls} · ${e.why}\n`;
  let expr = field;
  for (const e of entries) expr = `replace(${expr}, ${q(e.old)}, ${q(e.new)})`;
  sql += `UPDATE blog_posts SET ${field} = ${expr}\n WHERE slug = ${q(slug)};\n\n`;
}

const contentRows = new Set(
  LEDGER.filter((e) => (e.field ?? "content") === "content").map((e) => e.slug),
).size;
const excerptRows = new Set(
  LEDGER.filter((e) => e.field === "excerpt").map((e) => e.slug),
).size;

sql += `-- Post-flight: titles and publication state may not move, and exactly the
-- drafted rows may change in exactly the drafted columns.
DO $$
DECLARE n int;
BEGIN
  SELECT count(*) INTO n
    FROM blog_posts b JOIN ${BACKUP} k USING (id)
   WHERE b.title IS DISTINCT FROM k.title
      OR b.is_published IS DISTINCT FROM k.is_published;
  IF n <> 0 THEN RAISE EXCEPTION '% rows had title/is_published altered', n; END IF;

  SELECT count(*) INTO n
    FROM blog_posts b JOIN ${BACKUP} k USING (id)
   WHERE b.content IS DISTINCT FROM k.content;
  IF n <> ${contentRows} THEN RAISE EXCEPTION 'expected ${contentRows} content rewrites, got %', n; END IF;

  SELECT count(*) INTO n
    FROM blog_posts b JOIN ${BACKUP} k USING (id)
   WHERE b.excerpt IS DISTINCT FROM k.excerpt;
  IF n <> ${excerptRows} THEN RAISE EXCEPTION 'expected ${excerptRows} excerpt rewrites, got %', n; END IF;
END $$;

COMMIT;
`;

// The stored content contains no CR anywhere, so emit pure LF: a CRLF that
// crept in from an editor would silently break every multi-line target.
const lf = (t) => t.split(String.fromCharCode(13) + String.fromCharCode(10)).join(String.fromCharCode(10));
fs.writeFileSync(path.join(HERE, "migration.sql"), lf(sql));
fs.writeFileSync(path.join(HERE, "rollback.sql"), lf(`-- Rollback for ${ID}.
-- Restores \`content\` verbatim from the snapshot taken inside that migration.
-- Only \`content\` was ever written, so this is a complete reversal.

BEGIN;

UPDATE blog_posts b
   SET content = k.content, excerpt = k.excerpt
  FROM ${BACKUP} k
 WHERE b.id = k.id
   AND (b.content IS DISTINCT FROM k.content OR b.excerpt IS DISTINCT FROM k.excerpt);

COMMIT;
`));
console.log(`emitted migration.sql (${bySlug.size} rows, ${LEDGER.length} corrections) and rollback.sql`);

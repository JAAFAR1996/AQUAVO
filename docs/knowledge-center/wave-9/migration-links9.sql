<h2>النتريت: ليش السمكة تختنق والماء صافي</h2>
<p>النتريت يدخل من الغلاصم للدم ويتحد مع الهيموغلوبين فيحوّله إلى ميتهيموغلوبين، وهذا الشكل ما يقدر ينقل الأوكسجين. يعني الماء مليان أوكسجين والسمكة تختنق من جوّه. الدم يتحول للون بني، ولهذا يسمونه بالإنجليزية brown blood disease.</p>
<p><strong>العلامات اللي تنتبه لها:</strong> تنفس سريع، السمكة تلزم سطح الماء أو مخرج الفلتر، خمول، غلاصم لونها غامق أو بني.</p>
<p><strong>الإجراء الأول:</strong> تغيير ماء فوري وكافٍ، وإيقاف العلف يوم أو يومين لأن العلف يزيد الأمونيا. زيادة التهوية تساعد السمكة تتنفس بينما تنزّل النتريت.</p>
<p>معلومة كيميائية تفيدك بالفهم: أيون الكلوريد ينافس النتريت على نفس منافذ الامتصاص بالغلاصم، فوجود كلوريد بالماء يقلل دخول النتريت. لكن نسب الكلوريد المستخدمة بهذا الغرض جاية من تربية أسماك المزارع بأحجام وكثافات مختلفة تماماً عن حوض البيت، وما ننشر هنا أي جرعة. تغيير الماء يبقى الإجراء المضمون والآمن للهاوي. إذا ظهرت علامات مرضية إضافية، ابدأ من <a href="/fish-health-diagnosis">تشخيص صحة الأسماك</a>.</p>

<h2>التدوير بدون سمك، والتدوير مع سمك</h2>
<p><strong>بدون سمك</strong> هو الأسلوب الأنظف: تشغّل الفلتر والسخان على حوض بلا سمك، وتضيف مصدر أمونيا، وتفحص كل يومين لحد ما تصير الأمونيا صفر والنتريت صفر وتظهر النترات. ما في كائن حي يتعذب أثناء العملية.</p>
<p><strong>مع سمك</strong> يعني السمك يعيش داخل الأمونيا والنتريت بينما البكتيريا تتكاثر. إذا اضطريت له: عدد قليل جداً من السمك المتحمل، علف قليل، وفحص يومي مع تغيير ماء عند أي قراءة أمونيا أو نتريت.</p>
<p>التوقيت التقريبي في التدوير بدون سمك: النتريت غالباً يبدأ بالظهور بين اليوم الرابع عشر والعشرين، والدورة الكاملة تاخذ ستة أسابيع أو أكثر. هذا مدى وليس موعداً — يتغير كثيراً مع الحرارة وكمية الأمونيا وهل جبت ميديا من فلتر شغال.</p>
<p>أسرع طريقة مشروعة للاختصار هي نقل ميديا فلتر أو حصى من حوض مدوّر وسليم. وهذا بالضبط سبب أهمية <a href="/guides/quarantine">الحجر الصحي</a>: أي شي تنقله من حوض ثاني ينقل معه ما فيه.</p>

<h2>ليش تتوقف الدورة</h2>
<ul>
  <li><strong>الكلور أو الكلورامين بماء الحنفية.</strong> يقتل البكتيريا مثل ما يقتل الجراثيم. لازم معالج ماء قبل أي إضافة. وإذا كانت شبكتك تستخدم كلورامين، فمعالج يزيل الكلور فقط يترك شق الأمونيا موجوداً — انتبه لنوع المعالج. التفاصيل في <a href="/blog/how-to-treat-tap-water-for-fish-iraq">معالجة ماء الحنفية للأسماك في العراق</a>.</li>
  <li><strong>انخفاض الحموضة وضعف القساوة الكربونية.</strong> نشاط البكتيريا يضعف بشدة كلما نزل الـ pH ويقارب التوقف قرب 6.0. والـ KH الواطي — تحت حوالي 3 درجات — يخلي انهيار الـ pH أثناء التدوير احتمالاً وارداً، لأن عملية الأكسدة نفسها تستهلك القاعدية.</li>
  <li><strong>نتريت مرتفع جداً.</strong> فوق حدود 5 ملغم/لتر يبدأ النتريت نفسه يثبّط البكتيريا المفروض تعالجه، فتدخل بحلقة مغلقة. الحل تغيير ماء ينزّل الرقم، مو إضافة أمونيا أكثر.</li>
  <li><strong>غسل الميديا بماء الحنفية.</strong> أشهر خطأ. اغسل الإسفنج بماء مسحوب من الحوض نفسه، مو تحت الحنفية.</li>
  <li><strong>الأدوية والمضادات الحيوية.</strong> كثير منها يضرب البكتيريا النافعة، فتوقع رجوع الأمونيا بعد أي دورة علاج داخل الحوض.</li>
  <li><strong>انقطاع الكهرباء الطويل.</strong> بكتيريا الفلتر هوائية. إذا وقف جريان الماء ساعات طويلة بحرارة عالية، جزء منها يموت.</li>
</ul>

<h2>ظروف العراق تحديداً</h2>
<p>ثلاث ضغوط محلية تلتقي على نفس النقطة. حرارة الصيف ترفع أيض السمكة فتطلع أمونيا أكثر، وبنفس الوقت تقلل ذوبان الأوكسجين بالماء وترفع نسبة الأمونيا السامة. وانقطاع الكهرباء يوقف الفلتر بالضبط بالوقت اللي الحوض محتاجه أكثر شي. ومي الحنفية المعالجة تحتاج معالجاً مناسباً قبل كل تغيير ماء.</p>
<p>الاستنتاج العملي: بالصيف قلّل العلف، وقلّل الكثافة السمكية، وزد التهوية، وخلّي تغييرات الماء أصغر وأكثر تكراراً بدل تغيير كبير مفاجئ. ولحساب حجم حوضك وكمية الماء اللي تغيّرها فعلاً، استخدم <a href="/calculators">الحاسبات</a>.</p>

